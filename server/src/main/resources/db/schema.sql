CREATE TABLE IF NOT EXISTS ratings (
    id                  BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 评分ID
    borrow_id           BIGINT    REFERENCES borrow_requests(id),                 -- 借入申请ID
