-- 11. 操作日志表
-- =============================================================================
CREATE TABLE IF NOT EXISTS operation_logs (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 日志ID
    admin_id      BIGINT      NOT NULL REFERENCES users(id),                  -- 管理员ID
    tenant_id     BIGINT      NOT NULL REFERENCES tenants(id),               -- 所属小区ID
    action        VARCHAR(50) NOT NULL,                                      -- 操作动作
    target_type   VARCHAR(30),                                               -- 操作对象类型
    target_id     BIGINT,                                                     -- 操作对象ID
    detail        TEXT,                                                       -- 操作详情（JSON格式）
    created_at    TIMESTAMP   NOT NULL DEFAULT NOW()                         -- 创建时间
);
COMMENT ON TABLE  operation_logs                IS '操作日志表，记录B端管理员的所有管理操作';
COMMENT ON COLUMN operation_logs.id             IS '日志ID（自增主键）';
COMMENT ON COLUMN operation_logs.admin_id       IS '管理员ID，外键→users.id';
