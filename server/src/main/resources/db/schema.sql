-- =============================================================================
-- 社区互助闲置平台 — 数据库 Schema (PostgreSQL 17)
-- 12 张表，全部使用 BIGINT 自增主键，每个字段附带中文注释
-- =============================================================================

-- 非破坏式初始化：仅在表不存在时创建（IF NOT EXISTS），后端重启不清空数据。
-- 后续结构变更不改本文件语义，走 SchemaMigration.java / database-operator 幂等迁移。

-- =============================================================================
-- 1. 小区表
-- =============================================================================
CREATE TABLE IF NOT EXISTS tenants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 小区ID
    name        VARCHAR(100) NOT NULL,                                -- 小区名称
    created_at  TIMESTAMP    NOT NULL DEFAULT NOW()                   -- 创建时间
);
COMMENT ON TABLE  tenants                IS '小区表';
COMMENT ON COLUMN tenants.id             IS '小区ID（自增主键）';
COMMENT ON COLUMN tenants.name           IS '小区名称';
COMMENT ON COLUMN tenants.created_at     IS '创建时间';

-- =============================================================================
-- 2. 楼栋表
-- =============================================================================
CREATE TABLE IF NOT EXISTS buildings (
    id           BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 楼栋ID
    tenant_id    BIGINT    NOT NULL REFERENCES tenants(id),              -- 所属小区ID
    building_no  INTEGER   NOT NULL,                                     -- 楼栋号（如 3，展示时前端/后端拼"3栋"）
    created_at   TIMESTAMP NOT NULL DEFAULT NOW()                        -- 创建时间
);
COMMENT ON TABLE  buildings              IS '楼栋表';
COMMENT ON COLUMN buildings.id           IS '楼栋ID（自增主键）';
COMMENT ON COLUMN buildings.tenant_id    IS '所属小区ID，外键→tenants.id';
COMMENT ON COLUMN buildings.building_no  IS '楼栋号（数值，展示时拼"栋"后缀）';
COMMENT ON COLUMN buildings.created_at   IS '创建时间';

-- =============================================================================
-- 3. 单元表
-- =============================================================================
CREATE TABLE IF NOT EXISTS units (
    id          BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 单元ID
    building_id BIGINT    NOT NULL REFERENCES buildings(id),            -- 所属楼栋ID
    unit_no     INTEGER   NOT NULL,                                     -- 单元号（如 2，展示时拼"单元"）
    created_at  TIMESTAMP NOT NULL DEFAULT NOW()                        -- 创建时间
);
COMMENT ON TABLE  units                   IS '单元表';
COMMENT ON COLUMN units.id                IS '单元ID（自增主键）';
COMMENT ON COLUMN units.building_id       IS '所属楼栋ID，外键→buildings.id';
COMMENT ON COLUMN units.unit_no           IS '单元号（数值，展示时拼"单元"后缀）';
COMMENT ON COLUMN units.created_at        IS '创建时间';

-- =============================================================================
-- 4. 房间表
-- =============================================================================
CREATE TABLE IF NOT EXISTS rooms (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 房间ID
    unit_id     BIGINT      NOT NULL REFERENCES units(id),                -- 所属单元ID
    room_number VARCHAR(10) NOT NULL,                                     -- 房间号（如 1501）
    created_at  TIMESTAMP   NOT NULL DEFAULT NOW()                        -- 创建时间
);
COMMENT ON TABLE  rooms                   IS '房间表';
COMMENT ON COLUMN rooms.id                IS '房间ID（自增主键）';
COMMENT ON COLUMN rooms.unit_id           IS '所属单元ID，外键→units.id';
COMMENT ON COLUMN rooms.room_number       IS '房间号';
COMMENT ON COLUMN rooms.created_at        IS '创建时间';

-- =============================================================================
-- 5. 用户表
-- =============================================================================
CREATE TABLE IF NOT EXISTS users (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 用户ID
    room_id         BIGINT       REFERENCES rooms(id),                          -- 房间ID
    tenant_id       BIGINT,                                                      -- 所属小区ID
    openid          VARCHAR(64)  UNIQUE,                                         -- 微信OpenID
    username        VARCHAR(50)  UNIQUE,                                         -- 管理员用户名
    password_hash   VARCHAR(255),                                                -- 密码哈希（BCrypt）
    user_type       VARCHAR(20)  NOT NULL DEFAULT 'owner',                       -- 用户类型：'owner'(业主)/'tenant'(租客)/'admin'(普通管理员)/'super_admin'(超级管理员)
    name            VARCHAR(50),                                                 -- 姓名/昵称
    phone           VARCHAR(11),                                                 -- 手机号，11位
    phone_verified  BOOLEAN      NOT NULL DEFAULT FALSE,                         -- 手机号是否已验证
    avatar_url      VARCHAR(500),                                                -- 头像URL
    auth_status     VARCHAR(20)  NOT NULL DEFAULT 'pending',                     -- 认证状态：pending(待审核)/approved(已通过)/rejected(已拒绝)/registering(注册中)/banned(已封禁)
    banned_reason   VARCHAR(200),                                                -- 封禁原因，最多200字，仅auth_status=banned时有值
    doc_images      TEXT,                                                        -- 证件照片URL（JSON数组）
    reject_reason   VARCHAR(200),                                                -- 认证拒绝原因，最多200字，仅auth_status=rejected时有值
    token_version   INTEGER      NOT NULL DEFAULT 0,                             -- 令牌版本号（单会话登录控制）
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),                         -- 创建时间
    updated_at      TIMESTAMP    NOT NULL DEFAULT NOW(),                         -- 更新时间
    UNIQUE (phone, tenant_id),                                                  -- 同一小区内手机号唯一
    UNIQUE (room_id, user_type)                                                 -- 同一房间同一身份只能注册一个住户（业主与租客可并存）
);
COMMENT ON TABLE  users                     IS '用户表，存储所有用户（C端住户/B端管理员）';
COMMENT ON COLUMN users.id                  IS '用户ID（自增主键）';
COMMENT ON COLUMN users.room_id             IS '房间ID，外键→rooms.id，同一房间同一身份只能注册一个住户（业主与租客可并存）';
COMMENT ON COLUMN users.tenant_id           IS '所属小区ID，外键→tenants.id';
COMMENT ON COLUMN users.openid              IS '微信OpenID，C端用户唯一标识';
COMMENT ON COLUMN users.username            IS 'B端管理员用户名，管理员登录用';
COMMENT ON COLUMN users.password_hash       IS '密码哈希，BCrypt加密';
COMMENT ON COLUMN users.user_type           IS '用户类型：''owner''(业主)/''tenant''(租客)/''admin''(普通管理员)/''super_admin''(超级管理员)';
COMMENT ON COLUMN users.name                IS '姓名/昵称';
COMMENT ON COLUMN users.phone               IS '手机号，11位';
COMMENT ON COLUMN users.phone_verified      IS '手机号是否已验证：false(未验证)/true(已验证)';
COMMENT ON COLUMN users.avatar_url          IS '头像URL';
COMMENT ON COLUMN users.auth_status         IS '认证状态：pending(待审核)/approved(已通过)/rejected(已拒绝)/registering(注册中)/banned(已封禁)';
COMMENT ON COLUMN users.banned_reason       IS '封禁原因，最多200字，仅auth_status=banned时有值';
COMMENT ON COLUMN users.doc_images          IS '证件照片URL（JSON数组），注册时上传的房产证/租房合同';
COMMENT ON COLUMN users.reject_reason       IS '认证拒绝原因，最多200字，仅auth_status=rejected时有值';
COMMENT ON COLUMN users.token_version       IS '令牌版本号（单会话登录控制）';
COMMENT ON COLUMN users.created_at          IS '创建时间';
COMMENT ON COLUMN users.updated_at          IS '更新时间';

-- =============================================================================
-- 6. 闲置物品表
-- =============================================================================
CREATE TABLE IF NOT EXISTS idle_items (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 物品ID
    user_id         BIGINT         NOT NULL REFERENCES users(id),                  -- 发布用户ID
    tenant_id       BIGINT         NOT NULL REFERENCES tenants(id),               -- 所属小区ID
    post_type       VARCHAR(10)    NOT NULL DEFAULT 'LEND',                        -- 发布类型：LEND(闲置借出)/WANTED(需求借入)
    title           VARCHAR(100)   NOT NULL,                                       -- 标题
    description     VARCHAR(200),                                                  -- 描述，最多200字
    category        VARCHAR(20)    NOT NULL,                                       -- 分类：工具/电子产品/书籍/家居/运动/玩具/服饰/其他
    condition       VARCHAR(10)    NOT NULL DEFAULT 'normal',                      -- 成色：like-new(几乎全新)/normal(正常使用痕迹)/worn(有明显磨损)
    price           DECIMAL(10,2)  NOT NULL DEFAULT 0,                             -- 参考价格（元）
    images          TEXT,                                                          -- 图片URL（JSON数组），最多4张
    max_duration    INTEGER        DEFAULT 7,                                      -- 最大借出时长值
    duration_unit   VARCHAR(10)    NOT NULL DEFAULT 'day',                         -- 时长单位：day(天)/hour(小时)
    pickup_method   VARCHAR(30)    NOT NULL DEFAULT 'self_pickup',                 -- 取件方式：self_pickup(需自提)/both(自提或送上门)
    status          VARCHAR(20)    NOT NULL DEFAULT 'online',                      -- 状态：online(在线)/draft(草稿)/pending_review(待AI审核)/pending(待审批)/active(进行中)/completed(已完成)/offline(已下架)
    delist_reason   VARCHAR(200),                                                  -- 统一下架原因：AI审核原因、管理员驳回/下架原因、用户自行下架原因
    is_proxy        BOOLEAN        NOT NULL DEFAULT FALSE,                         -- 是否物业代发：false(否)/true(是)
    created_at      TIMESTAMP      NOT NULL DEFAULT NOW(),                         -- 创建时间
    updated_at      TIMESTAMP      NOT NULL DEFAULT NOW()                          -- 更新时间
);
COMMENT ON TABLE  idle_items                 IS '闲置物品表，C端用户发布的闲置借出/需求借入信息';
COMMENT ON COLUMN idle_items.id              IS '物品ID（自增主键）';
COMMENT ON COLUMN idle_items.user_id         IS '发布用户ID，外键→users.id';
COMMENT ON COLUMN idle_items.tenant_id       IS '所属小区ID，外键→tenants.id，用于按小区隔离数据';
COMMENT ON COLUMN idle_items.post_type       IS '发布类型：LEND(闲置借出)/WANTED(需求借入)';
COMMENT ON COLUMN idle_items.title           IS '标题';
COMMENT ON COLUMN idle_items.description     IS '描述，物品现状、使用痕迹、附件清单等，最多200字';
COMMENT ON COLUMN idle_items.category        IS '分类：工具/电子产品/书籍/家居/运动/玩具/服饰/其他（用户自定义）';
COMMENT ON COLUMN idle_items.condition       IS '成色：like-new(几乎全新)/normal(正常使用痕迹)/worn(有明显磨损)';
COMMENT ON COLUMN idle_items.price           IS '参考价格（元），用于损坏赔偿基准';
COMMENT ON COLUMN idle_items.images          IS '图片URL（JSON数组格式），最多4张';
COMMENT ON COLUMN idle_items.max_duration    IS '最大借出时长值，如7天=7';
COMMENT ON COLUMN idle_items.duration_unit   IS '时长单位：day(天)/hour(小时)';
COMMENT ON COLUMN idle_items.pickup_method   IS '取件方式：self_pickup(需自提)/both(自提或送上门)';
COMMENT ON COLUMN idle_items.status          IS '状态：online(在线)/draft(草稿)/pending_review(待AI审核)/pending(待审批)/active(进行中)/completed(已完成)/offline(已下架)';
COMMENT ON COLUMN idle_items.delist_reason   IS '统一下架原因：AI审核原因、管理员驳回/下架原因、用户自行下架原因';
COMMENT ON COLUMN idle_items.is_proxy        IS '是否物业代发：false(否)/true(是)';
COMMENT ON COLUMN idle_items.created_at      IS '创建时间';
COMMENT ON COLUMN idle_items.updated_at      IS '更新时间';

